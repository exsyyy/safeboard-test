export type Action = 'left' | 'right' | 'thrust' | 'fire';
export type InputState = Record<Action, boolean>;
export type Vec2 = { x: number; y: number };
export type Body = Vec2 & { vx: number; vy: number; radius: number };
export type Weapon = { heat: number; locked: boolean; cooldown: number };
export type Ship = Body & { angle: number; invulnerable: number; weapon: Weapon };
export type Rock = Body & { id: number; size: 1 | 2 | 3; angle: number; spin: number; shape: number[] };
export type Bullet = Body & { id: number; life: number; enemy: boolean };
export type Ufo = Body & { id: number; small: boolean; fireTimer: number; life: number };
export type Particle = Body & { life: number; maxLife: number; color: string };
export type GameConfig = {
  width: number;
  height: number;
  lives: number;
  acceleration: number;
  turnSpeed: number;
  maxSpeed: number;
  braking: number;
  bulletSpeed: number;
  shotInterval: number;
  heatPerShot: number;
  cooling: number;
  unlockHeat: number;
  rockScores: readonly number[];
};
export type GameState = {
  config: GameConfig;
  seed: number;
  nextId: number;
  time: number;
  status: 'playing' | 'gameover';
  score: number;
  lives: number;
  wave: number;
  waveTimer: number;
  ufoTimer: number;
  ship: Ship;
  asteroids: Rock[];
  bullets: Bullet[];
  ufos: Ufo[];
  particles: Particle[];
  events: ('shot' | 'explosion' | 'hit' | 'overheat' | 'wave')[];
};
